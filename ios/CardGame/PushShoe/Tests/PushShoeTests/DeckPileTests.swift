        XCTAssertEqual(top?.spoken, "Q♦️")
        XCTAssertEqual(top?.systemImageName, "suit.diamond.fill")
        XCTAssertEqual(top?.isRed, true)
        XCTAssertEqual(top?.rankSymbol, "Q")
        XCTAssertEqual(top?.suitSymbol, "♦️")
