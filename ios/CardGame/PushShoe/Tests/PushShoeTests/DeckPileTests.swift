    /// A two shows a wild mark on its face. The face stays the rank and suit. Other ranks do not.
    func testATwoShowsAWildMarkOnThatFace() {
        let clubs = CardSnapshot(id: 24, suit: .clubs, rank: .two, lockedUntilTurn: 0)
        let hearts = CardSnapshot(id: 25, suit: .hearts, rank: .two, lockedUntilTurn: 0)
        let diamonds = CardSnapshot(id: 26, suit: .diamonds, rank: .two, lockedUntilTurn: 3)
        let spades = CardSnapshot(id: 27, suit: .spades, rank: .two, lockedUntilTurn: 0)
        let noSuit = CardSnapshot(id: 28, suit: .none, rank: .two, lockedUntilTurn: 0)
        let three = CardSnapshot(id: 29, suit: .hearts, rank: .three, lockedUntilTurn: 0)
        let ace = CardSnapshot(id: 31, suit: .clubs, rank: .ace, lockedUntilTurn: 0)
        let ten = CardSnapshot(id: 30, suit: .spades, rank: .ten, lockedUntilTurn: 0)
        let clubsFace = NaturalFace.draw(clubs)
        let mark = WildMark.draw(clubs)

        XCTAssertEqual(clubsFace?.spoken, "2♣️")
        XCTAssertEqual(clubsFace?.systemImageName, "suit.club.fill")
        XCTAssertEqual(clubsFace?.isRed, false)
        XCTAssertEqual(mark?.spoken, "wild")
        XCTAssertNotEqual(mark?.spoken, "locked")
        XCTAssertNotEqual(clubsFace?.spoken, "2♣️ wild")
        XCTAssertEqual(WildMark.draw(hearts), mark)
        XCTAssertEqual(NaturalFace.draw(hearts)?.spoken, "2♥️")
        XCTAssertEqual(NaturalFace.draw(hearts)?.isRed, true)
        XCTAssertEqual(WildMark.draw(diamonds), mark)
        XCTAssertEqual(NaturalFace.draw(diamonds)?.spoken, "2♦️")
        XCTAssertEqual(WildMark.draw(spades), mark)
        XCTAssertEqual(NaturalFace.draw(spades)?.spoken, "2♠️")
        XCTAssertEqual(WildMark.draw(noSuit), mark)
        XCTAssertNil(NaturalFace.draw(noSuit))
        XCTAssertNil(JokerFace.draw(clubs))
        XCTAssertNil(WildMark.draw(three))
        XCTAssertNil(WildMark.draw(ace))
        XCTAssertNil(WildMark.draw(ten))
        XCTAssertEqual(NaturalFace.draw(three)?.spoken, "3♥️")
    }

