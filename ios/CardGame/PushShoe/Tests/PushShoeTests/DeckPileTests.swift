    /// The discard top uses their face. A queen is a diamond face. A joker is their joker face.
    /// The card under the top is not the face. An empty pile draws nothing.
    func testTheDiscardTopDrawsTheirFace() {
        let queenCard = CardSnapshot(id: 201, suit: .diamonds, rank: .queen, lockedUntilTurn: 0)
        let nineCard = CardSnapshot(id: 200, suit: .clubs, rank: .nine, lockedUntilTurn: 0)
        let jokerCard = CardSnapshot(id: 23, suit: .none, rank: .joker, lockedUntilTurn: 2)
        let suitedJoker = CardSnapshot(id: 23, suit: .hearts, rank: .joker, lockedUntilTurn: 0)
        let twoCard = CardSnapshot(id: 24, suit: .clubs, rank: .two, lockedUntilTurn: 0)
        let noSuit = CardSnapshot(id: 1, suit: .none, rank: .four, lockedUntilTurn: 0)
        let queen = DiscardFace.draw(queenCard)
        let nine = DiscardFace.draw(nineCard)
        let joker = DiscardFace.draw(jokerCard)

        XCTAssertEqual(queen?.spoken, "Q♦️")
        XCTAssertEqual(queen?.systemImageName, "suit.diamond.fill")
        XCTAssertEqual(queen?.isRed, true)
        XCTAssertEqual(queen?.rankSymbol, "Q")
        XCTAssertEqual(queen?.suitSymbol, "♦️")
        XCTAssertEqual(queen, DiscardFace.natural(NaturalFace.draw(queenCard)!))
        XCTAssertNotEqual(queen?.spoken, "Q♦")
        XCTAssertNil(WildMark.draw(queenCard))
        XCTAssertEqual(nine?.spoken, "9♣️")
        XCTAssertNotEqual(nine, queen)
        XCTAssertNil(DiscardFace.drawTop([]))
        XCTAssertEqual(DiscardFace.drawTop([queenCard]), queen)
        XCTAssertEqual(DiscardFace.drawTop([nineCard, queenCard]), queen)
        XCTAssertNotEqual(DiscardFace.drawTop([nineCard, queenCard]), nine)
        XCTAssertNil(DiscardFace.drawTop([queenCard, noSuit]))
        XCTAssertEqual(joker?.spoken, "Joker")
        XCTAssertEqual(joker?.systemImageName, "star.fill")
        XCTAssertEqual(joker?.isRed, false)
        XCTAssertEqual(joker?.rankSymbol, "Joker")
        XCTAssertEqual(joker?.suitSymbol, "")
        XCTAssertEqual(joker, DiscardFace.joker(JokerFace.draw(jokerCard)!))
        XCTAssertEqual(DiscardFace.draw(suitedJoker), joker)
        XCTAssertNotEqual(joker?.spoken, "Joker wild")
        XCTAssertNil(NaturalFace.draw(jokerCard))
        XCTAssertNil(DiscardFace.draw(noSuit))
        XCTAssertEqual(DiscardFace.draw(twoCard)?.spoken, "2♣️")
        XCTAssertNotEqual(DiscardFace.draw(twoCard)?.spoken, "2♣️ wild")
        XCTAssertNil(DiscardFace.shown(in: Game()))
    }

