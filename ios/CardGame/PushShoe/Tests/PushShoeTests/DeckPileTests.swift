    /// Seat 0's cards stay in the order Rust holds them. A two and a joker keep the wild word.
    /// A card with no face is left out. A lift does not play or hit.
    func testSeat0HandSitsInTheirLayoutAndNothingLifts() {
        let eight = CardSnapshot(id: 21, suit: .diamonds, rank: .eight, lockedUntilTurn: 0)
        let king = CardSnapshot(id: 22, suit: .spades, rank: .king, lockedUntilTurn: 0)
        let joker = CardSnapshot(id: 23, suit: .none, rank: .joker, lockedUntilTurn: 2)
        let suitedJoker = CardSnapshot(id: 99, suit: .hearts, rank: .joker, lockedUntilTurn: 0)
        let two = CardSnapshot(id: 24, suit: .clubs, rank: .two, lockedUntilTurn: 0)
        let three = CardSnapshot(id: 30, suit: .hearts, rank: .three, lockedUntilTurn: 0)
        let noSuit = CardSnapshot(id: 1, suit: .none, rank: .four, lockedUntilTurn: 0)
        let queen = CardSnapshot(id: 201, suit: .diamonds, rank: .queen, lockedUntilTurn: 0)
        let hand = LocalHand.layout([eight, king, joker, two])
        let reversed = LocalHand.layout([two, joker, king, eight])
        let withBlank = LocalHand.layout([eight, noSuit, king])
        let fresh = Game()
        let exhibit = Game.exhibitSetAndRun()
        let before = exhibit.tableSnapshot()
        let lifted = LocalHand.lift(cardId: 21, in: exhibit)

        XCTAssertEqual(hand.slots.map(\.id), [21, 22, 23, 24])
        XCTAssertEqual(hand.slots.map(\.spoken), ["8♦️", "K♠️", "Joker", "2♣️"])
        XCTAssertNil(hand.slots[0].wild)
        XCTAssertNil(hand.slots[1].wild)
        XCTAssertEqual(hand.slots[2].wild?.spoken, "wild")
        XCTAssertEqual(hand.slots[3].wild?.spoken, "wild")
        XCTAssertNotEqual(hand.slots[2].spoken, "Joker wild")
        XCTAssertNotEqual(hand.slots[2].spoken, "Joker, locked")
        XCTAssertNotEqual(hand.slots[3].spoken, "2♣️ wild")
        XCTAssertFalse(hand.allowsLift)
        XCTAssertEqual(reversed.slots.map(\.id), [24, 23, 22, 21])
        XCTAssertEqual(reversed.slots.map(\.spoken), ["2♣️", "Joker", "K♠️", "8♦️"])
        XCTAssertNotEqual(reversed, hand)
        XCTAssertEqual(withBlank.slots.map(\.id), [21, 22])
        XCTAssertEqual(withBlank.slots.map(\.spoken), ["8♦️", "K♠️"])
        XCTAssertFalse(withBlank.allowsLift)
        XCTAssertTrue(LocalHand.layout([]).slots.isEmpty)
        XCTAssertFalse(LocalHand.layout([]).allowsLift)
        XCTAssertEqual(LocalHand.layout([suitedJoker]).slots.map(\.id), [99])
        XCTAssertEqual(LocalHand.layout([suitedJoker]).slots[0].spoken, "Joker")
        XCTAssertEqual(LocalHand.layout([suitedJoker]).slots[0].wild?.spoken, "wild")
        XCTAssertEqual(LocalHand.layout([three]).slots[0].spoken, "3♥️")
        XCTAssertNil(LocalHand.layout([three]).slots[0].wild)
        XCTAssertEqual(LocalHand.layout([queen]).slots[0].spoken, "Q♦️")
        XCTAssertNil(LocalHand.layout([queen]).slots[0].wild)
        XCTAssertFalse(LocalHand.layout([queen]).allowsLift)
        XCTAssertTrue(LocalHand.shown(in: fresh).slots.isEmpty)
        XCTAssertFalse(LocalHand.shown(in: fresh).allowsLift)
        XCTAssertEqual(fresh.tableSnapshot().hand.count, 0)
        XCTAssertNil(fresh.tableSnapshot().discardTop)
        XCTAssertEqual(LocalHand.shown().slots.map(\.id), [21, 22, 23, 24])
        XCTAssertFalse(LocalHand.shown().allowsLift)
        XCTAssertEqual(LocalHand.shown(in: exhibit).slots.map(\.spoken), hand.slots.map(\.spoken))
        XCTAssertFalse(LocalHand.shown(in: exhibit).slots.map(\.id).contains(1))
        XCTAssertFalse(LocalHand.shown(in: exhibit).slots.map(\.id).contains(90))
        XCTAssertFalse(LocalHand.shown(in: exhibit).slots.map(\.id).contains(200))
        XCTAssertFalse(LocalHand.shown(in: exhibit).slots.map(\.id).contains(201))
        XCTAssertEqual(lifted.slots.map(\.id), [21, 22, 23, 24])
        XCTAssertFalse(lifted.allowsLift)
        XCTAssertEqual(exhibit.tableSnapshot(), before)
        XCTAssertEqual(exhibit.getDeckSize(), 108)
        XCTAssertEqual(exhibit.tableSnapshot().board.count, 2)
        XCTAssertEqual(exhibit.tableSnapshot().hand.map(\.id), [21, 22, 23, 24])
        XCTAssertEqual(exhibit.tableSnapshot().discardTop?.rank, .queen)
        XCTAssertEqual(LocalHand.lift(cardId: 90, in: fresh).slots.count, 0)
        XCTAssertEqual(fresh.getDeckSize(), 108)
    }

